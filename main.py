# Problem 12: Highly Divisible Triangular Number
# ============================================================================
# What is the value of the first triangle number to have over n divisors?
# Reference: https://projecteuler.net/problem=12

def count_divisors(n: int) -> int:
    """Count the number of divisors of n."""
    divisor_count = 0
    sqrt_n = int(math.sqrt(n)) + 1
    for i in range(1, sqrt_n):
        if n % i == 0:
            divisor_count += 2
    if int(math.sqrt(n)) ** 2 == n:
        divisor_count -= 1
    return divisor_count


def problem12(min_divisors: int) -> int:
    """Find first triangle number with over min_divisors divisors."""
    triangular_num = 0
    i = 0

    while count_divisors(triangular_num) < min_divisors:
        i += 1
        triangular_num += i

    return triangular_num


