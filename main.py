# Problem 5: Smallest Multiple
# ============================================================================
# 2520 is the smallest number that can be divided by each of the numbers
# from 1 to 10 without any remainder.
# What is the smallest positive number evenly divisible by 1 to n?
# Reference: https://projecteuler.net/problem=5

def problem5(n: int) -> int:
    """Find the smallest positive number evenly divisible by 1 to n."""
    return reduce(math.lcm, range(1, n + 1))

# ============================================================================
# Problem 6: Sum Square Difference
# ============================================================================
# The sum of the squares of the first ten natural numbers is 385.
# The square of the sum is 3025.
# Find the difference between the sum of squares and square of sum.
# Reference: https://projecteuler.net/problem=6

def problem6(n: int) -> int:
    """Calculate difference between sum of squares and square of sum."""
    numbers = range(1, n + 1)
    sum_of_squares = sum(i ** 2 for i in numbers)
    square_of_sum = sum(numbers) ** 2
    return square_of_sum - sum_of_squares


