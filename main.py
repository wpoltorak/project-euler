def largest_product_in_series(digits_str: str, series_length: int) -> int:
    """Find the largest product of series_length consecutive digits."""
    digit_list = [int(d) for d in digits_str]
    max_product = 0

    for i in range(len(digit_list) - series_length + 1):
        product = reduce(operator.mul, digit_list[i:i + series_length], 1)
        max_product = max(max_product, product)

    return max_product


