# Problem 9: Special Pythagorean Triplet
# ============================================================================
# A Pythagorean triplet is a set of three natural numbers a < b < c
# where a^2 + b^2 = c^2. Find the product abc where a + b + c = n.
# Reference: https://projecteuler.net/problem=9

def find_pythagorean_triplet(n: int) -> Tuple[int, int, int]:
    """Find Pythagorean triplet where a + b + c = n."""
    for m in range(2, int(math.sqrt(n)) + 1):
        for k in range(1, m):
            a = m * m - k * k
            b = 2 * m * k
            c = m * m + k * k
            if a + b + c == n:
                return tuple(sorted([a, b, c]))
    return (0, 0, 0)


def problem9(n: int) -> int:
    """Return the product abc of Pythagorean triplet summing to n."""
    a, b, c = find_pythagorean_triplet(n)
    return a * b * c


