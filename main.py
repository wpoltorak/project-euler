# Problem 10: Summation of Primes
# ============================================================================
# Find the sum of all primes below n.
# Reference: https://projecteuler.net/problem=10
# Uses Sieve of Eratosthenes: https://en.wikipedia.org/wiki/Sieve_of_Eratosthenes

def sieve_of_eratosthenes(limit: int) -> List[int]:
    """Return all prime numbers below limit using Sieve of Eratosthenes."""
    is_prime = [True] * (limit + 1)
    is_prime[0] = is_prime[1] = False

    for p in range(2, int(math.sqrt(limit)) + 1):
        if is_prime[p]:
            for i in range(p * p, limit + 1, p):
                is_prime[i] = False

    return [num for num, prime in enumerate(is_prime) if prime]


def problem10(n: int) -> int:
    """Return the sum of all primes below n."""
    return sum(sieve_of_eratosthenes(n))


