# Problem 14: Longest Collatz Sequence
# ============================================================================
# Which starting number, under one million, produces the longest chain?
# Reference: https://projecteuler.net/problem=14

def collatz_chain_length(n: int) -> int:
    """Calculate the length of the Collatz sequence starting at n."""
    length = 1
    while n != 1:
        length += 1
        n = n // 2 if n % 2 == 0 else 3 * n + 1
    return length


def problem14(limit: int) -> int:
    """Find the starting number under limit with longest Collatz chain."""
    return max(
        range(1, limit),
        key=collatz_chain_length
    )


